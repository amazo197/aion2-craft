let lang = 'en';
const listeners = [];

export function getLang() { return lang; }

export function t(key, vars) {
  const s = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m)) : s;
}

function plurSuffix(l, n) {
  if (l !== 'ru') return '';
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return '_1';
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return '_2';
  return '_5';
}

// Plural-aware count: "{n} рецепт / рецепта / рецептов". EN has a single form.
export function tn(key, n) {
  const suffix = plurSuffix(lang, n);
  const s = (DICT[lang] && DICT[lang][key + suffix]) ?? (DICT[lang] && DICT[lang][key]) ?? DICT.en[key + suffix] ?? DICT.en[key] ?? key;
  return s.replace('{n}', n);
}

export function applyStatic() {
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-value]')) el.value = t(el.dataset.i18nValue);
}

export function onLangChange(fn) { listeners.push(fn); }

export function setLang(l) {
  lang = DICT[l] ? l : 'en';
  try { localStorage.setItem('lang', lang); } catch (e) { /* private mode */ }
  document.documentElement.lang = lang;
  applyStatic();
  const sel = document.getElementById('lang');
  if (sel) sel.value = lang;
  for (const fn of listeners) fn(lang);
}

export function initI18n() {
  let saved = null;
  try { saved = localStorage.getItem('lang'); } catch (e) { /* private mode */ }
  const nav = String(navigator.language || 'en').slice(0, 2).toLowerCase();
  setLang(saved || (nav === 'ru' ? 'ru' : 'en'));
}
